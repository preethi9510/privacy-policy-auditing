import pandas as pd
import re

# Defining the original rule-based logic to compare against the AI model
def rule_based_label(text):
    if not isinstance(text, str): return 0
    text_str = text.lower().strip()
    BANNED_START = ('menu ', 'updated ', 'effective ', 'page ', 'section ', 'table of ', 'visit ', 'follow ', 'copyright ', 'portions of ')
    if text_str.startswith(BANNED_START) or len(text_str) < 45: return 0
    GEOGRAPHY_EXCLUSION = r"(eu |eea|switzerland|california|ccpa|gdpr|united kingdom|member state)"
    if re.search(GEOGRAPHY_EXCLUSION, text_str): return 0
    COPPA_SUBJECTS = r"(child|minor|under 13|under 18|age|birthday|parent|guardian|consent|verifi)"
    DATA_ACTIONS = r"(collect|use|share|disclose|right|request|contact|identif|provide|store|protect|remove|delete)"
    if text_str.endswith('?'): return 0
    if re.search(COPPA_SUBJECTS, text_str) and re.search(DATA_ACTIONS, text_str): return 1
    if re.search(DATA_ACTIONS, text_str) and len(text_str) > 80: return 1
    return 0

# Loading the AI model results
df = pd.read_csv("IoT_AI_Labeled_Results.csv", encoding="utf-8-sig")


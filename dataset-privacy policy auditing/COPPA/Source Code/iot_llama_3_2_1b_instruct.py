def formatting_prompts_func(examples):
    sentences = examples["text"]
    labels    = examples["coppa_label"]
    texts = []
    for sentence, label in zip(sentences, labels):
        # We fill in the template and add the EOS (End of String) token
        text = prompt_style.format(sentence, label) + tokenizer.eos_token
        texts.append(text)
    return { "text" : texts, }

